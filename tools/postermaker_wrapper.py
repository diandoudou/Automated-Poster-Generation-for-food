from pathlib import Path

def generate_poster(image_path, mask_path, prompt, texts, output_dir=None):
    """
    This is the unified interface for LayoutPlanner. For now, implement a "mock version";
    later, if you actually use the PosterMaker model, replace the internal TODOs with real calls.
    Parameters:
      - image_path: Path to the main image generated by the Visual Designer (string)
      - mask_path: Path to the mask (can be None)
      - prompt: The text prompt composed from the brief (string)
      - texts: Text layout information, as a list, for example:
        [
          {"content": "Chocolate Cake", "pos": [150, 1400, 930, 1500]},
          ...
        ]
      - output_dir: Output directory; defaults to outputs/posters if not provided
    Returns:
      - poster_image_path: Path to the "composited poster" image (string)
    """
    if output_dir is None:
        output_dir = Path("outputs/posters")
    else:
        output_dir = Path(output_dir)

    output_dir.mkdir(parents=True, exist_ok=True)

    # TODO: do not actually run the model; just create a mock file to prove the pipeline works
    dummy_output = output_dir / "poster_mock.png"

    # TODO: in the future, PosterMaker calls can be integrated here
    if not dummy_output.exists():
        import numpy as np
        import cv2
        img = np.full((800, 600, 3), 255, dtype=np.uint8)
        cv2.putText(
            img,
            "Mock Poster",
            (50, 400),
            cv2.FONT_HERSHEY_SIMPLEX,
            2,
            (0, 0, 0),
            3,
            cv2.LINE_AA,
        )
        cv2.imwrite(str(dummy_output), img)
    return str(dummy_output)
